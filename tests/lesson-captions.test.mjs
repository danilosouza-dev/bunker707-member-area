import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import "./support/resolve-extensionless-ts.mjs";

const {
  buildStoredCaptionTrack,
  normalizeStoredCaptionCues,
  resolveLessonCaptions
} = await import("../src/server/video/lesson-captions.ts");

const receiverCaptionsRouteSource = await readFile(
  new URL("../src/app/api/tv/receiver/[sessionId]/captions/route.ts", import.meta.url),
  "utf8"
);

const youtubeResult = {
  cues: [{ durationSeconds: 2, startSeconds: 1, text: "do YouTube" }],
  tracks: [{ isAutoGenerated: true, languageCode: "pt", name: "Portugues (automatico)" }]
};

test("stored cues are normalized: invalid rows dropped, end time converted to duration, sorted by start", () => {
  const cues = normalizeStoredCaptionCues([
    { startSeconds: 10, endSeconds: 12.5, text: "  segunda  " },
    { startSeconds: 0, durationSeconds: 3, text: "primeira" },
    { startSeconds: 5, durationSeconds: 1, text: "   " },
    { startSeconds: -1, durationSeconds: 1, text: "negativa" },
    { startSeconds: 7, endSeconds: 6, text: "termina antes de comecar" },
    { startSeconds: "8", durationSeconds: 1, text: "tempo em texto" },
    null,
    "texto solto",
    { startSeconds: 20, durationSeconds: 0, text: "duracao zero e valida" }
  ]);

  assert.deepEqual(cues, [
    { durationSeconds: 3, startSeconds: 0, text: "primeira" },
    { durationSeconds: 2.5, startSeconds: 10, text: "segunda" },
    { durationSeconds: 0, startSeconds: 20, text: "duracao zero e valida" }
  ]);
  assert.deepEqual(normalizeStoredCaptionCues(null), []);
  assert.deepEqual(normalizeStoredCaptionCues({ startSeconds: 0, durationSeconds: 1, text: "objeto" }), []);
});

test("stored cue text is capped and the track names the platform or the YouTube import", () => {
  const [cue] = normalizeStoredCaptionCues([{ startSeconds: 0, durationSeconds: 1, text: "x".repeat(5_000) }]);

  assert.equal(cue.text.length, 2_000);
  assert.deepEqual(buildStoredCaptionTrack({ language: "pt-BR", source: "upload" }), {
    isAutoGenerated: false,
    languageCode: "pt-BR",
    name: "Legenda da plataforma"
  });
  assert.equal(buildStoredCaptionTrack({ language: "en", source: "youtube" }).isAutoGenerated, true);
});

test("the stored transcript wins and YouTube is never contacted", async () => {
  let youtubeCalls = 0;
  const stored = {
    cues: [{ durationSeconds: 1, startSeconds: 0, text: "da plataforma" }],
    track: buildStoredCaptionTrack({ language: "pt-BR", source: "paste" })
  };

  const result = await resolveLessonCaptions({
    fetchCaptions: async () => {
      youtubeCalls += 1;
      return youtubeResult;
    },
    language: "pt",
    loadStoredCaptions: async () => stored,
    videoId: "abcdefghijk"
  });

  assert.equal(youtubeCalls, 0);
  assert.equal(result.source, "platform");
  assert.deepEqual(result.cues, stored.cues);
  assert.deepEqual(result.tracks, [stored.track]);
});

test("without a stored transcript the YouTube captions are used, and an empty answer is reported as none", async () => {
  const calls = [];
  const withCues = await resolveLessonCaptions({
    fetchCaptions: async (input) => {
      calls.push(input);
      return youtubeResult;
    },
    language: "pt",
    loadStoredCaptions: async () => null,
    videoId: "abcdefghijk"
  });
  const withoutCues = await resolveLessonCaptions({
    fetchCaptions: async () => ({ cues: [], tracks: [] }),
    language: "pt",
    loadStoredCaptions: async () => ({ cues: [], track: buildStoredCaptionTrack({ language: "pt", source: "upload" }) }),
    videoId: "abcdefghijk"
  });

  assert.deepEqual(calls, [{ language: "pt", videoId: "abcdefghijk" }]);
  assert.equal(withCues.source, "youtube");
  assert.deepEqual(withCues.cues, youtubeResult.cues);
  assert.equal(withoutCues.source, "none");
  assert.deepEqual(withoutCues.cues, []);
});

test("a failure reading the stored transcript is reported and falls back to YouTube; YouTube errors propagate", async () => {
  const reported = [];
  const databaseError = new Error("banco fora");

  const result = await resolveLessonCaptions({
    fetchCaptions: async () => youtubeResult,
    language: "pt",
    loadStoredCaptions: async () => {
      throw databaseError;
    },
    onStoredCaptionsError: (error) => reported.push(error),
    videoId: "abcdefghijk"
  });

  assert.deepEqual(reported, [databaseError]);
  assert.equal(result.source, "youtube");

  await assert.rejects(
    resolveLessonCaptions({
      fetchCaptions: async () => {
        throw new Error("youtube fora");
      },
      language: "pt",
      loadStoredCaptions: async () => null,
      videoId: "abcdefghijk"
    }),
    /youtube fora/
  );
});

test("without a video id and without a stored transcript nothing is fetched", async () => {
  let youtubeCalls = 0;
  const result = await resolveLessonCaptions({
    fetchCaptions: async () => {
      youtubeCalls += 1;
      return youtubeResult;
    },
    language: "pt",
    loadStoredCaptions: async () => null,
    videoId: ""
  });

  assert.equal(youtubeCalls, 0);
  assert.deepEqual(result, { cues: [], source: "none", tracks: [] });
});

test("the TV receiver caption route reads the stored transcript of the session lesson first", () => {
  assert.match(receiverCaptionsRouteSource, /loadStoredCaptions: \(\) => getActiveLessonTranscriptCaptions\(lessonId\)/);
  assert.match(receiverCaptionsRouteSource, /const lessonId = data\.lesson\.id/);
  assert.match(receiverCaptionsRouteSource, /fetchCaptions: fetchYouTubeCaptions/);
  assert.ok(
    receiverCaptionsRouteSource.indexOf("getTvReceiverSession(") < receiverCaptionsRouteSource.indexOf("await resolveLessonCaptions"),
    "the receiver session and lesson access must be validated before any caption source is read"
  );
});
