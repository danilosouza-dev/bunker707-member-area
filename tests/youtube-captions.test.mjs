test("caption fetch uses no-store, returns public tracks and translated json3 cues", async () => {
  const calls = [];
  const watchPage = createWatchPage([
    {
      baseUrl: `https://www.youtube.com/api/timedtext?v=${videoId}&lang=en&signature=abc`,
      isDefault: true,
      isTranslatable: true,
      languageCode: "en",
      name: { simpleText: "English" }
    }
  ]);
  const fetchImpl = async (input, init) => {
    const url = new URL(input.toString());
    calls.push({ init, url });

    if (url.pathname === "/watch") {
      return new Response(watchPage, { status: 200 });
    }

    return new Response(JSON.stringify({
      events: [{ dDurationMs: 1_250, segs: [{ utf8: "Legenda traduzida" }], tStartMs: 500 }]
    }), { status: 200 });
  };

  const result = await fetchYouTubeCaptions({ fetchImpl, language: "pt", videoId });

  assert.deepEqual(result, {
    cues: [{ durationSeconds: 1.25, startSeconds: 0.5, text: "Legenda traduzida" }],
    tracks: [{ isAutoGenerated: false, languageCode: "en", name: "English" }]
  });
  assert.equal(calls.length, 2);
  assert.equal(calls[0].url.origin, "https://www.youtube.com");
  assert.equal(calls[0].url.pathname, "/watch");
  assert.equal(calls[0].url.searchParams.get("v"), videoId);
  assert.equal(calls[1].url.pathname, "/api/timedtext");
  assert.equal(calls[1].url.searchParams.get("fmt"), "json3");
  assert.equal(calls[1].url.searchParams.get("tlang"), "pt");
  assert.ok(calls.every(({ init }) => init.cache === "no-store"));
  assert.ok(calls.every(({ init }) => init.redirect === "error"));
});

