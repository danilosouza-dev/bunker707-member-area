const videoId = "abcdefghijk";

function createWatchPage(captionTracks) {
  return `<script>var ytInitialPlayerResponse = ${JSON.stringify({
    captions: {
      playerCaptionsTracklistRenderer: { captionTracks }
    }
  })};</script>`;
}

test("youtube caption input accepts only a strict video id and BCP-47-like language", () => {
  assert.equal(isValidYouTubeVideoId(videoId), true);
  assert.equal(isValidYouTubeVideoId("dQw4w9WgXcQ"), true);
  assert.equal(isValidYouTubeVideoId("abcdefghij"), false);
  assert.equal(isValidYouTubeVideoId("abcdefghijk?x"), false);
  assert.equal(isValidYouTubeVideoId("../abcdefgh"), false);

  assert.equal(normalizeYouTubeCaptionLanguage("pt-br"), "pt-BR");
  assert.equal(normalizeYouTubeCaptionLanguage("es-419"), "es-419");
  assert.equal(normalizeYouTubeCaptionLanguage(" pt "), "pt");
  assert.equal(normalizeYouTubeCaptionLanguage("pt/../../admin"), null);
  assert.equal(normalizeYouTubeCaptionLanguage(""), null);
});

