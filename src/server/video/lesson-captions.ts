import type {
  YouTubeCaptionCue,
  YouTubeCaptionTrack,
  YouTubeCaptionsResult
} from "./youtube-captions";

// Legenda da aula: primeiro a transcricao guardada na plataforma (lesson_transcripts, enviada ou
// colada pelo produtor no admin, ou importada do YouTube quando a importacao funcionou), depois
// a legenda ao vivo do YouTube. Em producao o servidor sai de um IP de datacenter e o YouTube
// costuma negar a pagina do video e a faixa de legenda, entao a copia guardada e o caminho
// confiavel. Este modulo nao acessa banco nem rede: as duas fontes chegam por injecao, o que
// deixa a regra testavel no Node.

export type LessonCaptionsSource = "none" | "platform" | "youtube";

export type LessonCaptionsResult = YouTubeCaptionsResult & {
  source: LessonCaptionsSource;
};

export type StoredLessonCaptions = {
  cues: YouTubeCaptionCue[];
  track: YouTubeCaptionTrack;
};

const maxStoredCues = 20_000;
const maxCueTextLength = 2_000;
const maxCueStartSeconds = 7 * 24 * 60 * 60;

function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function readSeconds(value: unknown) {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

/**
 * Converte o JSON de `lesson_transcripts.cues` nas cues que o player entende, descartando
 * entradas sem tempo ou sem texto. Aceita `durationSeconds` ou, na falta dele, `endSeconds`.
 */
export function normalizeStoredCaptionCues(value: unknown): YouTubeCaptionCue[] {
  if (!Array.isArray(value)) {
    return [];
  }

  const cues: YouTubeCaptionCue[] = [];

  for (const rawCue of value) {
    if (cues.length >= maxStoredCues) {
      break;
    }

    if (!isRecord(rawCue)) {
      continue;
    }

    const startSeconds = readSeconds(rawCue.startSeconds);
    const text = typeof rawCue.text === "string" ? rawCue.text.trim() : "";

    if (startSeconds === null || startSeconds < 0 || startSeconds > maxCueStartSeconds || !text) {
      continue;
    }

    const endSeconds = readSeconds(rawCue.endSeconds);
    const durationSeconds = readSeconds(rawCue.durationSeconds)
      ?? (endSeconds === null ? null : endSeconds - startSeconds);

    if (durationSeconds === null || durationSeconds < 0) {
      continue;
    }

    cues.push({
      durationSeconds,
      startSeconds,
      text: text.slice(0, maxCueTextLength)
    });
  }

  return cues.sort((left, right) => left.startSeconds - right.startSeconds);
}

export function buildStoredCaptionTrack({
  language,
  source
}: {
  language: string;
  source: string;
}): YouTubeCaptionTrack {
  const importedFromYouTube = source === "youtube";

  return {
    isAutoGenerated: importedFromYouTube,
    languageCode: language,
    name: importedFromYouTube ? "Legenda importada do YouTube" : "Legenda da plataforma"
  };
}

export async function resolveLessonCaptions({
  fetchCaptions,
  language,
  loadStoredCaptions,
  onStoredCaptionsError,
  videoId
}: {
  /** Legenda ao vivo do YouTube; so e chamada quando nao ha legenda guardada. */
  fetchCaptions: (input: { language: string; videoId: string }) => Promise<YouTubeCaptionsResult>;
  language: string;
  /** Transcricao ativa da aula na plataforma, ja normalizada; `null` quando nao ha. */
  loadStoredCaptions: () => Promise<StoredLessonCaptions | null>;
  /** Falha ao ler a copia guardada nao derruba a legenda: cai para o YouTube e avisa aqui. */
  onStoredCaptionsError?: (error: unknown) => void;
  videoId: string;
}): Promise<LessonCaptionsResult> {
  let stored: StoredLessonCaptions | null = null;

  try {
    stored = await loadStoredCaptions();
  } catch (error) {
    onStoredCaptionsError?.(error);
    stored = null;
  }

  if (stored && stored.cues.length > 0) {
    return { cues: stored.cues, source: "platform", tracks: [stored.track] };
  }

  if (!videoId) {
    return { cues: [], source: "none", tracks: [] };
  }

  const youtube = await fetchCaptions({ language, videoId });

  return {
    cues: youtube.cues,
    source: youtube.cues.length > 0 ? "youtube" : "none",
    tracks: youtube.tracks
  };
}
